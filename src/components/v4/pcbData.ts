export const toPath = (pts: number[][]) => "M" + pts.map((p) => p.join(" ")).join(" L");

type Pin = [number, number, "h" | "v"];

export type Ic = {
  id: string;
  at: number;
  body: [number, number, number, number]; // x, y, w, h
  label: string;
  pins: Pin[];
};

const vPins = (xs: number[], yTop: number, yBottom: number): Pin[] =>
  xs.flatMap((x): Pin[] => [[x, yTop, "v"], [x, yBottom, "v"]]);
const hPins = (ys: number[], xLeft: number, xRight: number): Pin[] =>
  ys.flatMap((y): Pin[] => [[xLeft, y, "h"], [xRight, y, "h"]]);

